// 拼装用户 prompt：用户问题 + 匹配范文 + 写作任务
export function buildUserPrompt(userMessage, matchedArticles) {
  const refs = matchedArticles
    .slice(0, 3)
    .map(
      (a, i) =>
        `【参考范文 ${i + 1}】《${a.title}》\n- 摘要：${a.summary}\n- 核心事实：${a.facts}\n- 文风特点：${a.style}\n- 标签：${a.tags}`
    )
    .join("\n\n");

  return `## 用户主题
${userMessage}

## 参考范文（基于知识库匹配）
${refs}

## 写作任务
请基于以上主题，写一篇完整的梁巍风格中国产业报道。要求：
1. 至少 3000 字
2. 包含 frontmatter（YAML 格式）
3. 嵌入至少 3-5 个经典化用 + 借用语
4. 数字密度 ≥ 30
5. 结尾押韵或押题

直接输出 Markdown 格式的完整稿件，不需要解释。`;
}